"""Operational commands.

    python -m app.cli init [--port 5432] [--admin-url URL]   write .env with generated secrets
    python -m app.cli bootstrap     create roles, database and schema (needs DATABASE_ADMIN_URL)
    python -m app.cli migrate       apply schema migrations (needs DATABASE_OWNER_URL)
    python -m app.cli setup         bootstrap + migrate
    python -m app.cli seed          load demo organizations (development only)
    python -m app.cli verify        verify every organization's audit chain; exit 1 on failure
    python -m app.cli check         print configuration problems; exit 1 if any
    python -m app.cli create-platform-admin --email E --name N   first platform super admin (MFA enforced)
"""

from __future__ import annotations

import argparse
import secrets
import sys

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict

from app.config import ROOT_DIR, get_settings
from app.errors import ApiError
from app.security import random_key_b64

OWNER_ROLE = "prov_owner"
APP_ROLE = "prov_app"
PLATFORM_ROLE = "prov_platform"
SCHEMA = "prov"


def cmd_init(args: argparse.Namespace) -> None:
    env = ROOT_DIR / ".env"
    if env.exists() and not args.force:
        print(f"{env} already exists; leaving it alone (use --force to overwrite).")
        return
    owner_pw, app_pw, platform_pw = secrets.token_urlsafe(24), secrets.token_urlsafe(24), secrets.token_urlsafe(24)
    host, port, db = args.host, args.port, args.database
    admin = args.admin_url or f"postgresql://postgres@{host}:{port}/postgres"
    lines = [
        "# Generated by `python -m app.cli init`. Development values; never commit this file.",
        "ENVIRONMENT=development",
        "",
        f"DATABASE_URL=postgresql://{APP_ROLE}:{app_pw}@{host}:{port}/{db}",
        f"DATABASE_OWNER_URL=postgresql://{OWNER_ROLE}:{owner_pw}@{host}:{port}/{db}",
        f"DATABASE_ADMIN_URL={admin}",
        f"DATABASE_PLATFORM_URL=postgresql://{PLATFORM_ROLE}:{platform_pw}@{host}:{port}/{db}",
        "",
        f"JWT_SECRET={secrets.token_urlsafe(48)}",
        f"DATA_ENCRYPTION_KEY={random_key_b64()}",
        f"CHECKPOINT_SIGNING_KEY={random_key_b64()}",
        "",
        "# Local development conveniences. All of these must be off in production.",
        "WORKERS_ENABLED=true",
        "COOKIE_SECURE=false",
        "WEBHOOK_ALLOW_PRIVATE_URLS=true",
        "WEBHOOK_ALLOW_HTTP=true",
        "",
        f"DEMO_PASSWORD={secrets.token_urlsafe(12)}",
        "",
    ]
    env.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {env}")


def _role_and_password(url: str, expected: str, name: str) -> str:
    info = conninfo_to_dict(url)
    if info.get("user") != expected:
        sys.exit(f"{name} must connect as role '{expected}' (the migrations grant privileges to that name).")
    if not info.get("password"):
        sys.exit(f"{name} has no password.")
    return str(info["password"])


def cmd_bootstrap(_: argparse.Namespace) -> None:
    s = get_settings()
    if not s.database_admin_url:
        sys.exit("DATABASE_ADMIN_URL is not set (a superuser connection, used only by this command).")
    owner_pw = _role_and_password(s.database_owner_url, OWNER_ROLE, "DATABASE_OWNER_URL")
    app_pw = _role_and_password(s.database_url, APP_ROLE, "DATABASE_URL")
    # The platform console role is optional to *use*, but always created so migrations can grant to it.
    # Without DATABASE_PLATFORM_URL it is created NOLOGIN, so it cannot be used at all.
    platform_pw = (_role_and_password(s.database_platform_url, PLATFORM_ROLE, "DATABASE_PLATFORM_URL")
                   if s.database_platform_url else None)
    dbname = str(conninfo_to_dict(s.database_url)["dbname"])

    with psycopg.connect(s.database_admin_url, autocommit=True) as conn:
        for role, password in ((OWNER_ROLE, owner_pw), (APP_ROLE, app_pw)):
            exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (role,)).fetchone()
            verb = "ALTER" if exists else "CREATE"
            conn.execute(sql.SQL(
                "{} ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS NOREPLICATION PASSWORD {}"
            ).format(sql.SQL(verb), sql.Identifier(role), sql.Literal(password)))
            print(f"  role {role}: {'updated' if exists else 'created'}")
        exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (PLATFORM_ROLE,)).fetchone()
        login = sql.SQL("LOGIN PASSWORD {}").format(sql.Literal(platform_pw)) if platform_pw else sql.SQL("NOLOGIN")
        conn.execute(sql.SQL("{} ROLE {} {} NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS NOREPLICATION").format(
            sql.SQL("ALTER" if exists else "CREATE"), sql.Identifier(PLATFORM_ROLE), login))
        print(f"  role {PLATFORM_ROLE}: {'updated' if exists else 'created'}{'' if platform_pw else ' (NOLOGIN: DATABASE_PLATFORM_URL not set)'}")
        if not conn.execute("SELECT 1 FROM pg_database WHERE datname = %s", (dbname,)).fetchone():
            conn.execute(sql.SQL("CREATE DATABASE {} OWNER {} ENCODING 'UTF8' TEMPLATE template0")
                         .format(sql.Identifier(dbname), sql.Identifier(OWNER_ROLE)))
            print(f"  database {dbname}: created")
        conn.execute(sql.SQL("REVOKE ALL ON DATABASE {} FROM PUBLIC").format(sql.Identifier(dbname)))
        conn.execute(sql.SQL("GRANT CONNECT ON DATABASE {} TO {}, {}, {}").format(
            sql.Identifier(dbname), sql.Identifier(OWNER_ROLE), sql.Identifier(APP_ROLE), sql.Identifier(PLATFORM_ROLE)))

    admin_in_db = {**conninfo_to_dict(s.database_admin_url), "dbname": dbname}
    with psycopg.connect(**admin_in_db, autocommit=True) as conn:  # type: ignore[arg-type]
        conn.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {} AUTHORIZATION {}")
                     .format(sql.Identifier(SCHEMA), sql.Identifier(OWNER_ROLE)))
        conn.execute("REVOKE CREATE ON SCHEMA public FROM PUBLIC")
        for role in (OWNER_ROLE, APP_ROLE, PLATFORM_ROLE):
            conn.execute(sql.SQL("ALTER ROLE {} IN DATABASE {} SET search_path = {}").format(
                sql.Identifier(role), sql.Identifier(dbname), sql.Identifier(SCHEMA)))
    print(f"  schema {SCHEMA}: ready")


def cmd_migrate(args: argparse.Namespace) -> None:
    from alembic import command
    from alembic.config import Config

    cfg = Config(str(ROOT_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT_DIR / "migrations"))
    command.upgrade(cfg, getattr(args, "revision", None) or "head")
    print("  migrations: up to date")


def cmd_setup(args: argparse.Namespace) -> None:
    cmd_bootstrap(args)
    cmd_migrate(args)


def cmd_seed(_: argparse.Namespace) -> None:
    from app.services.demo import seed_demo

    seed_demo()


def cmd_verify(_: argparse.Namespace) -> None:
    from app.db import close_pool, system_session, tenant_session
    from app.services.integrity import verify_tenant

    failed = 0
    with system_session() as db:
        tenants = [r["worker_tenants"] for r in db.all("SELECT prov.worker_tenants(false)")]
    for tid in tenants:
        with tenant_session(tid, None, "system:cli", "cli-verify") as db:
            result = verify_tenant(db, tid)
        status = "ok" if result["ok"] else f"FAILED at {result['first_bad_seq']}: {result['reason']}"
        print(f"  tenant {tid}: {result['checked']} records, {result['checkpoints']['checked']} checkpoints - {status}")
        failed += 0 if result["ok"] else 1
    close_pool()
    if failed:
        sys.exit(1)


def cmd_create_platform_admin(args: argparse.Namespace) -> None:
    """First (or recovery) super admin. Refuses when an active super admin exists: further operators are
    added in the console by a super admin, with MFA and an audit record. Never a shared account."""
    from app.db import close_pool, platform_session
    from app.services import platform as platform_svc

    password = secrets.token_urlsafe(15)
    with platform_session() as db:
        if db.scalar("SELECT count(*) FROM platform_users WHERE role = 'super_admin' AND is_active"):
            sys.exit("An active super admin already exists. Add operators from the platform console instead.")
        try:
            new_id = platform_svc.create_operator(db, args.email, args.name, "super_admin", password, "cli:bootstrap")
        except ApiError as exc:
            sys.exit(exc.detail)
        db.commit()
        platform_svc.append(db, actor="cli:bootstrap", actor_id=None, action="operator.created",
                            details={"operator_id": new_id, "email": args.email.lower(), "role": "super_admin"})
    close_pool()
    print(f"  super admin {args.email.lower()} created (id {new_id})")
    print(f"  temporary password (shown once): {password}")
    print("  sign in at /platform; TOTP MFA enrolment is required at first sign-in")


def cmd_check(_: argparse.Namespace) -> None:
    problems = get_settings().problems()
    for p in problems:
        print(f"  ! {p}")
    if problems:
        sys.exit(1)
    print("  configuration ok")


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m app.cli", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("init")
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=5432)
    p.add_argument("--database", default="provenance")
    p.add_argument("--admin-url", default="")
    p.add_argument("--force", action="store_true")
    p.set_defaults(fn=cmd_init)
    sub.add_parser("bootstrap").set_defaults(fn=cmd_bootstrap)
    p = sub.add_parser("migrate")
    p.add_argument("revision", nargs="?", default="head")
    p.set_defaults(fn=cmd_migrate)
    sub.add_parser("setup").set_defaults(fn=cmd_setup)
    sub.add_parser("seed").set_defaults(fn=cmd_seed)
    sub.add_parser("verify").set_defaults(fn=cmd_verify)
    sub.add_parser("check").set_defaults(fn=cmd_check)
    p = sub.add_parser("create-platform-admin")
    p.add_argument("--email", required=True)
    p.add_argument("--name", required=True)
    p.set_defaults(fn=cmd_create_platform_admin)
    args = parser.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
