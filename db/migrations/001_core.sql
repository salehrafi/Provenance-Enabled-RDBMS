-- Composite (tenant_id, id) foreign keys make cross-tenant references impossible at the
-- database level, not just in application code.
CREATE TABLE orders (
  order_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL
                CONSTRAINT fk_orders_tenant REFERENCES tenants(tenant_id),
  customer_id   NUMBER NOT NULL,
  status        VARCHAR2(12) DEFAULT 'CREATED' NOT NULL
                CONSTRAINT ck_orders_status CHECK
                (status IN ('CREATED', 'PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'REFUNDED')),
  total_amount  NUMBER(12,2) DEFAULT 0 NOT NULL CONSTRAINT ck_orders_total CHECK (total_amount >= 0),
  currency      CHAR(3) DEFAULT 'USD' NOT NULL,
  notes         VARCHAR2(500),
  created_at    TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  updated_at    TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT uq_orders_tenant UNIQUE (tenant_id, order_id),
  CONSTRAINT fk_orders_customer FOREIGN KEY (tenant_id, customer_id)
    REFERENCES customers(tenant_id, customer_id)
)
/

CREATE INDEX ix_orders_status ON orders(tenant_id, status)
/

CREATE INDEX ix_orders_customer ON orders(tenant_id, customer_id)
/

CREATE TABLE order_items (
  order_id    NUMBER NOT NULL,
  product_id  NUMBER NOT NULL,
  tenant_id   NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL,
  quantity    NUMBER(10,2) NOT NULL CONSTRAINT ck_items_qty CHECK (quantity > 0),
  unit_price  NUMBER(12,2) NOT NULL CONSTRAINT ck_items_price CHECK (unit_price >= 0),
  line_total  NUMBER(14,2) GENERATED ALWAYS AS (ROUND(quantity * unit_price, 2)) VIRTUAL,
  CONSTRAINT pk_order_items PRIMARY KEY (order_id, product_id),
  CONSTRAINT fk_items_order FOREIGN KEY (tenant_id, order_id) REFERENCES orders(tenant_id, order_id),
  CONSTRAINT fk_items_product FOREIGN KEY (tenant_id, product_id) REFERENCES products(tenant_id, product_id)
)
/

CREATE INDEX ix_items_product ON order_items(tenant_id, product_id)
/

CREATE TABLE payments (
  payment_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL,
  order_id    NUMBER NOT NULL,
  amount      NUMBER(12,2) NOT NULL CONSTRAINT ck_payments_amount CHECK (amount > 0),
  method      VARCHAR2(10) NOT NULL
              CONSTRAINT ck_payments_method CHECK (method IN ('CARD', 'CASH', 'BKASH', 'NAGAD', 'BANK')),
  status      VARCHAR2(10) DEFAULT 'CAPTURED' NOT NULL
              CONSTRAINT ck_payments_status CHECK (status IN ('CAPTURED', 'VOID', 'REFUNDED')),
  reference   VARCHAR2(80),
  created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_payments_order FOREIGN KEY (tenant_id, order_id) REFERENCES orders(tenant_id, order_id)
)
/

CREATE INDEX ix_payments_order ON payments(tenant_id, order_id)
/
