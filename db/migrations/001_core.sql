-- 001_core: application context, tenants, users, business tables.
-- Convention: every statement is terminated by a line containing only "/".

-- Application context package. The API calls set_ctx at the start of every request, so
-- triggers and VPD policies know which tenant and which human is acting, even though
-- every request shares the same PROV_APP database account.
CREATE OR REPLACE PACKAGE ctx_pkg AUTHID DEFINER AS
  PROCEDURE set_ctx(p_tenant_id  IN NUMBER,
                    p_user_id    IN NUMBER,
                    p_username   IN VARCHAR2,
                    p_request_id IN VARCHAR2);
  PROCEDURE set_change_request(p_change_request_id IN NUMBER);
  PROCEDURE clear_ctx;
END ctx_pkg;
/

CREATE OR REPLACE PACKAGE BODY ctx_pkg AS
  PROCEDURE set_ctx(p_tenant_id  IN NUMBER,
                    p_user_id    IN NUMBER,
                    p_username   IN VARCHAR2,
                    p_request_id IN VARCHAR2) IS
  BEGIN
    DBMS_SESSION.CLEAR_ALL_CONTEXT('PROV_CTX');
    DBMS_SESSION.SET_CONTEXT('PROV_CTX', 'TENANT_ID',  TO_CHAR(p_tenant_id));
    DBMS_SESSION.SET_CONTEXT('PROV_CTX', 'USER_ID',    TO_CHAR(p_user_id));
    DBMS_SESSION.SET_CONTEXT('PROV_CTX', 'USERNAME',   p_username);
    DBMS_SESSION.SET_CONTEXT('PROV_CTX', 'REQUEST_ID', p_request_id);
  END set_ctx;

  PROCEDURE set_change_request(p_change_request_id IN NUMBER) IS
  BEGIN
    DBMS_SESSION.SET_CONTEXT('PROV_CTX', 'CHANGE_REQUEST_ID', TO_CHAR(p_change_request_id));
  END set_change_request;

  PROCEDURE clear_ctx IS
  BEGIN
    DBMS_SESSION.CLEAR_ALL_CONTEXT('PROV_CTX');
  END clear_ctx;
END ctx_pkg;
/

CREATE TABLE tenants (
  tenant_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(120) NOT NULL,
  slug        VARCHAR2(60)  NOT NULL CONSTRAINT uq_tenants_slug UNIQUE,
  plan        VARCHAR2(20)  DEFAULT 'FREE' NOT NULL
              CONSTRAINT ck_tenants_plan CHECK (plan IN ('FREE', 'PRO', 'ENTERPRISE')),
  created_at  TIMESTAMP(6)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
)
/

CREATE TABLE tenant_settings (
  tenant_id                 NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL
                            CONSTRAINT pk_tenant_settings PRIMARY KEY
                            CONSTRAINT fk_settings_tenant REFERENCES tenants(tenant_id),
  currency                  CHAR(3)      DEFAULT 'USD' NOT NULL,
  approval_price_change_pct NUMBER(6,2)  DEFAULT 20   NOT NULL,
  price_change_alert_pct    NUMBER(6,2)  DEFAULT 30   NOT NULL,
  discount_alert_pct        NUMBER(6,2)  DEFAULT 20   NOT NULL,
  large_refund_amount       NUMBER(12,2) DEFAULT 1000 NOT NULL,
  rapid_change_count        NUMBER(4)    DEFAULT 5    NOT NULL,
  rapid_change_minutes      NUMBER(4)    DEFAULT 10   NOT NULL
)
/

CREATE TABLE app_users (
  user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      NUMBER NOT NULL CONSTRAINT fk_users_tenant REFERENCES tenants(tenant_id),
  email          VARCHAR2(254) NOT NULL CONSTRAINT uq_users_email UNIQUE,
  full_name      VARCHAR2(120) NOT NULL,
  password_hash  VARCHAR2(255) NOT NULL,
  role           VARCHAR2(10)  DEFAULT 'viewer' NOT NULL
                 CONSTRAINT ck_users_role CHECK (role IN ('admin', 'staff', 'viewer')),
  is_active      CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT ck_users_active CHECK (is_active IN ('Y', 'N')),
  created_at     TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  last_login_at  TIMESTAMP(6)
)
/

CREATE INDEX ix_users_tenant ON app_users(tenant_id)
/

CREATE TABLE customers (
  customer_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL
               CONSTRAINT fk_customers_tenant REFERENCES tenants(tenant_id),
  name         VARCHAR2(120) NOT NULL,
  email        VARCHAR2(254) NOT NULL,
  phone        VARCHAR2(30),
  created_at   TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT uq_customers_email  UNIQUE (tenant_id, email),
  CONSTRAINT uq_customers_tenant UNIQUE (tenant_id, customer_id)
)
/

CREATE TABLE products (
  product_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL
               CONSTRAINT fk_products_tenant REFERENCES tenants(tenant_id),
  sku          VARCHAR2(40)  NOT NULL,
  name         VARCHAR2(120) NOT NULL,
  price        NUMBER(12,2)  NOT NULL CONSTRAINT ck_products_price CHECK (price >= 0),
  active_flag  CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT ck_products_active CHECK (active_flag IN ('Y', 'N')),
  created_at   TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT uq_products_sku    UNIQUE (tenant_id, sku),
  CONSTRAINT uq_products_tenant UNIQUE (tenant_id, product_id)
)
/

