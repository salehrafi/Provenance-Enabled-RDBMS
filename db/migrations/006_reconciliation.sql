-- 006_reconciliation: compare an upstream system's current state with the evidence we hold.

CREATE TABLE reconciliations (
  recon_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL
                 CONSTRAINT fk_recon_tenant REFERENCES tenants(tenant_id),
  source_id      NUMBER NOT NULL,
  entity         VARCHAR2(30) NOT NULL,
  as_of          TIMESTAMP(6) NOT NULL,
  complete       CHAR(1) DEFAULT 'N' NOT NULL CONSTRAINT ck_recon_complete CHECK (complete IN ('Y', 'N')),
  total_records  NUMBER NOT NULL,
  matched        NUMBER NOT NULL,
  mismatched     NUMBER NOT NULL,
  missing        NUMBER NOT NULL,
  unexpected     NUMBER NOT NULL,
  created_by     VARCHAR2(254) NOT NULL,
  created_at     TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT fk_recon_source FOREIGN KEY (tenant_id, source_id) REFERENCES sources(tenant_id, source_id)
)
/

CREATE INDEX ix_recon_source ON reconciliations(tenant_id, source_id, created_at)
/

-- Only discrepancies are stored; matched records are counted, not listed.
CREATE TABLE reconciliation_items (
  item_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recon_id     NUMBER NOT NULL CONSTRAINT fk_recon_items REFERENCES reconciliations(recon_id),
  tenant_id    NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL,
  external_id  VARCHAR2(100) NOT NULL,
  outcome      VARCHAR2(12) NOT NULL
               CONSTRAINT ck_recon_outcome CHECK (outcome IN ('MISMATCH', 'MISSING', 'UNEXPECTED')),
  details      CLOB CONSTRAINT ck_recon_items_json CHECK (details IS JSON)
)
/

CREATE INDEX ix_recon_items ON reconciliation_items(recon_id)
/

BEGIN
  FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list('RECONCILIATIONS', 'RECONCILIATION_ITEMS'))) LOOP
    DBMS_RLS.ADD_POLICY(
      object_schema   => 'PROV_OWNER',
      object_name     => t.name,
      policy_name     => 'TENANT_ISOLATION',
      function_schema => 'PROV_OWNER',
      policy_function => 'VPD_PKG.TENANT_PREDICATE',
      statement_types => 'SELECT,INSERT,UPDATE,DELETE',
      update_check    => TRUE,
      policy_type     => DBMS_RLS.STATIC);
  END LOOP;
END;
