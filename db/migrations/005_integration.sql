-- 005_integration: API keys, registered sources, and a validated ingestion path for external events.

-- API keys for machines. Only a SHA-256 hash of the secret is stored; the full key is shown once.
-- Not VPD-protected: authentication must find a key before the tenant is known. Every query
-- filters by tenant_id explicitly.
CREATE TABLE api_keys (
  key_id        VARCHAR2(16)  PRIMARY KEY,
  tenant_id     NUMBER        NOT NULL CONSTRAINT fk_api_keys_tenant REFERENCES tenants(tenant_id),
  name          VARCHAR2(100) NOT NULL,
  secret_hash   VARCHAR2(64)  NOT NULL,
  scopes        VARCHAR2(200) NOT NULL,
  created_by    VARCHAR2(254),
  created_at    TIMESTAMP(6)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  last_used_at  TIMESTAMP(6),
  revoked_at    TIMESTAMP(6)
)
/

CREATE INDEX ix_api_keys_tenant ON api_keys(tenant_id)
/

-- A registered upstream system (legacy shop, ERP, Shopify...). The capture method and trust
-- level are set by an administrator here, never by the sender of an event, so a sender cannot
-- claim a higher trust level than it was granted.
CREATE TABLE sources (
  source_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL
                 CONSTRAINT fk_sources_tenant REFERENCES tenants(tenant_id),
  code           VARCHAR2(60)  NOT NULL,
  name           VARCHAR2(120) NOT NULL,
  capture_method VARCHAR2(20)  NOT NULL
                 CONSTRAINT ck_sources_capture CHECK (capture_method IN ('CDC', 'TRIGGER', 'API', 'CSV_IMPORT', 'POLLING', 'MANUAL')),
  trust_level    VARCHAR2(10)  NOT NULL
                 CONSTRAINT ck_sources_trust CHECK (trust_level IN ('HIGH', 'MEDIUM', 'LOW')),
  status         VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL
                 CONSTRAINT ck_sources_status CHECK (status IN ('ACTIVE', 'PAUSED')),
  created_at     TIMESTAMP(6)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  last_event_at  TIMESTAMP(6),
  CONSTRAINT uq_sources_code UNIQUE (tenant_id, code),
  CONSTRAINT uq_sources_tenant UNIQUE (tenant_id, source_id)
)
/

-- Every accepted external event. (tenant_id, source_id, source_event_id) is unique, which makes
-- retries safe: a duplicate is detected by the database, not by application code.
CREATE TABLE external_events (
  event_pk         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        NUMBER NOT NULL CONSTRAINT fk_ext_events_tenant REFERENCES tenants(tenant_id),
  source_id        NUMBER NOT NULL,
  source_event_id  VARCHAR2(200) NOT NULL,
  event_type       VARCHAR2(120) NOT NULL,
  subject          VARCHAR2(200),
  entity           VARCHAR2(30),
  external_id      VARCHAR2(100),
  occurred_at      TIMESTAMP(6)  NOT NULL,
  received_at      TIMESTAMP(6)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  capture_method   VARCHAR2(20)  NOT NULL,
  trust_level      VARCHAR2(10)  NOT NULL,
  payload          CLOB CONSTRAINT ck_ext_events_json CHECK (payload IS JSON),
  request_id       VARCHAR2(64),
  CONSTRAINT fk_ext_events_source FOREIGN KEY (tenant_id, source_id) REFERENCES sources(tenant_id, source_id),
  CONSTRAINT uq_ext_events_id UNIQUE (tenant_id, source_id, source_event_id)
)
/

CREATE INDEX ix_ext_events_entity ON external_events(tenant_id, entity, external_id)
/

-- Validated write path. The API may call this procedure but cannot write to audit_log directly.
-- It checks the source belongs to the tenant and is active, stores the event, and records it in
-- the hash-chained audit log (which also emits an outbox event for webhooks).
CREATE OR REPLACE PACKAGE ingest_pkg AUTHID DEFINER AS
  PROCEDURE record_external(p_source_code IN  VARCHAR2,
                            p_event_id    IN  VARCHAR2,
                            p_type        IN  VARCHAR2,
                            p_subject     IN  VARCHAR2,
                            p_entity      IN  VARCHAR2,
                            p_external_id IN  VARCHAR2,
                            p_occurred    IN  VARCHAR2,
                            p_payload     IN  VARCHAR2,
                            p_event_pk    OUT NUMBER,
                            p_trust       OUT VARCHAR2,
                            p_capture     OUT VARCHAR2);
END ingest_pkg;
/

CREATE OR REPLACE PACKAGE BODY ingest_pkg AS
  PROCEDURE record_external(p_source_code IN  VARCHAR2,
                            p_event_id    IN  VARCHAR2,
                            p_type        IN  VARCHAR2,
                            p_subject     IN  VARCHAR2,
                            p_entity      IN  VARCHAR2,
                            p_external_id IN  VARCHAR2,
                            p_occurred    IN  VARCHAR2,
                            p_payload     IN  VARCHAR2,
                            p_event_pk    OUT NUMBER,
                            p_trust       OUT VARCHAR2,
                            p_capture     OUT VARCHAR2) IS
    v_tenant    NUMBER := TO_NUMBER(SYS_CONTEXT('PROV_CTX', 'TENANT_ID'));
    v_source_id NUMBER;
    v_status    VARCHAR2(10);
  BEGIN
    BEGIN
      SELECT source_id, status, trust_level, capture_method
        INTO v_source_id, v_status, p_trust, p_capture
        FROM sources WHERE tenant_id = v_tenant AND code = p_source_code;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20010, 'Unknown source: ' || p_source_code);
    END;
    IF v_status <> 'ACTIVE' THEN
      RAISE_APPLICATION_ERROR(-20011, 'Source is paused: ' || p_source_code);
    END IF;

    INSERT INTO external_events (tenant_id, source_id, source_event_id, event_type, subject, entity,
                                 external_id, occurred_at, capture_method, trust_level, payload, request_id)
    VALUES (v_tenant, v_source_id, p_event_id, p_type, p_subject, p_entity, p_external_id,
            TO_TIMESTAMP(p_occurred, 'YYYY-MM-DD"T"HH24:MI:SS.FF6'), p_capture, p_trust, p_payload,
            SYS_CONTEXT('PROV_CTX', 'REQUEST_ID'))
    RETURNING event_pk INTO p_event_pk;

    UPDATE sources SET last_event_at = SYS_EXTRACT_UTC(SYSTIMESTAMP) WHERE source_id = v_source_id;

    audit_pkg.log_change(v_tenant, 'external_event', TO_CHAR(p_event_pk), 'INSERT', NULL, p_payload);
  END record_external;
END ingest_pkg;
/

-- Tenant isolation for the new tenant-owned tables (api_keys is looked up before a tenant is known).
DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(30);
  v_tables t_list := t_list('SOURCES', 'EXTERNAL_EVENTS');
BEGIN
  FOR i IN 1 .. v_tables.COUNT LOOP
    DBMS_RLS.ADD_POLICY(
      object_schema   => 'PROV_OWNER',
      object_name     => v_tables(i),
      policy_name     => 'TENANT_ISOLATION',
      function_schema => 'PROV_OWNER',
      policy_function => 'VPD_PKG.TENANT_PREDICATE',
      statement_types => 'SELECT,INSERT,UPDATE,DELETE',
      update_check    => TRUE,
      policy_type     => DBMS_RLS.STATIC);
  END LOOP;
END;
/

