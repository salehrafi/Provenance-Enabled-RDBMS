-- 004_features: alerts, maker-checker approvals, webhooks, VPD tenant isolation, grants.

CREATE TABLE alerts (
  alert_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL,
  rule_code    VARCHAR2(20)  NOT NULL,
  severity     VARCHAR2(10)  NOT NULL
               CONSTRAINT ck_alerts_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
  entity       VARCHAR2(30),
  entity_id    VARCHAR2(100),
  title        VARCHAR2(300) NOT NULL,
  details      CLOB CONSTRAINT ck_alerts_json CHECK (details IS JSON),
  fingerprint  VARCHAR2(200) NOT NULL,
  status       VARCHAR2(12) DEFAULT 'OPEN' NOT NULL
               CONSTRAINT ck_alerts_status CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
  created_at   TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  updated_at   TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  updated_by   VARCHAR2(254),
  CONSTRAINT uq_alerts_fingerprint UNIQUE (tenant_id, fingerprint)
)
/

CREATE INDEX ix_alerts_status ON alerts(tenant_id, status)
/

CREATE TABLE change_requests (
  change_request_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL,
  entity             VARCHAR2(30) NOT NULL,
  entity_id          VARCHAR2(100) NOT NULL,
  change_type        VARCHAR2(30) NOT NULL,
  payload            CLOB NOT NULL CONSTRAINT ck_cr_json CHECK (payload IS JSON),
  reason             VARCHAR2(500),
  status             VARCHAR2(10) DEFAULT 'PENDING' NOT NULL
                     CONSTRAINT ck_cr_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
  requested_by_id    NUMBER NOT NULL,
  requested_by       VARCHAR2(254) NOT NULL,
  requested_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  reviewed_by_id     NUMBER,
  reviewed_by        VARCHAR2(254),
  reviewed_at        TIMESTAMP(6),
  review_note        VARCHAR2(500),
  -- the database itself refuses self-approval
  CONSTRAINT ck_cr_four_eyes CHECK (reviewed_by_id IS NULL OR reviewed_by_id <> requested_by_id)
)
/

CREATE INDEX ix_cr_status ON change_requests(tenant_id, status)
/

CREATE TABLE webhooks (
  webhook_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL,
  url          VARCHAR2(500) NOT NULL,
  secret       VARCHAR2(100) NOT NULL,
  event_types  VARCHAR2(500) DEFAULT '*' NOT NULL,
  description  VARCHAR2(200),
  is_active    CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT ck_webhooks_active CHECK (is_active IN ('Y', 'N')),
  created_at   TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
)
/

CREATE TABLE webhook_deliveries (
  delivery_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        NUMBER DEFAULT SYS_CONTEXT('PROV_CTX', 'TENANT_ID') NOT NULL,
  webhook_id       NUMBER NOT NULL CONSTRAINT fk_deliveries_webhook REFERENCES webhooks(webhook_id),
  event_id         NUMBER NOT NULL CONSTRAINT fk_deliveries_event REFERENCES outbox_events(event_id),
  status           VARCHAR2(10) DEFAULT 'PENDING' NOT NULL
                   CONSTRAINT ck_deliveries_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'DEAD')),
  attempts         NUMBER(3) DEFAULT 0 NOT NULL,
  response_code    NUMBER(3),
  last_error       VARCHAR2(1000),
  next_attempt_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  created_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  delivered_at     TIMESTAMP(6),
  CONSTRAINT uq_delivery UNIQUE (webhook_id, event_id)
)
/

CREATE INDEX ix_deliveries_due ON webhook_deliveries(tenant_id, status, next_attempt_at)
/

-- Virtual Private Database: Oracle appends this predicate to every query on the protected
-- tables. With no tenant in the context, queries return nothing (fail closed).
CREATE OR REPLACE PACKAGE vpd_pkg AUTHID DEFINER AS
  FUNCTION tenant_predicate(p_schema IN VARCHAR2, p_object IN VARCHAR2) RETURN VARCHAR2;
END vpd_pkg;
/

CREATE OR REPLACE PACKAGE BODY vpd_pkg AS
  FUNCTION tenant_predicate(p_schema IN VARCHAR2, p_object IN VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN 'tenant_id = TO_NUMBER(SYS_CONTEXT(''PROV_CTX'', ''TENANT_ID''))';
  END tenant_predicate;
END vpd_pkg;
/

DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(200);
  -- table name : statement types
  v_tables t_list := t_list(
    'CUSTOMERS:SELECT,INSERT,UPDATE,DELETE',
    'PRODUCTS:SELECT,INSERT,UPDATE,DELETE',
    'ORDERS:SELECT,INSERT,UPDATE,DELETE',
    'ORDER_ITEMS:SELECT,INSERT,UPDATE,DELETE',
    'PAYMENTS:SELECT,INSERT,UPDATE,DELETE',
    'TENANT_SETTINGS:SELECT,INSERT,UPDATE,DELETE',
    'ALERTS:SELECT,INSERT,UPDATE,DELETE',
    'CHANGE_REQUESTS:SELECT,INSERT,UPDATE,DELETE',
    'WEBHOOKS:SELECT,INSERT,UPDATE,DELETE',
    'WEBHOOK_DELIVERIES:SELECT,INSERT,UPDATE,DELETE',
    'OUTBOX_EVENTS:SELECT,UPDATE,DELETE',
    'AUDIT_LOG:SELECT');
  v_name  VARCHAR2(30);
  v_types VARCHAR2(100);
BEGIN
  FOR i IN 1 .. v_tables.COUNT LOOP
    v_name  := SUBSTR(v_tables(i), 1, INSTR(v_tables(i), ':') - 1);
    v_types := SUBSTR(v_tables(i), INSTR(v_tables(i), ':') + 1);
    DBMS_RLS.ADD_POLICY(
      object_schema   => 'PROV_OWNER',
      object_name     => v_name,
      policy_name     => 'TENANT_ISOLATION',
      function_schema => 'PROV_OWNER',
      policy_function => 'VPD_PKG.TENANT_PREDICATE',
      statement_types => v_types,
      update_check    => TRUE,
      policy_type     => DBMS_RLS.STATIC);
  END LOOP;
END;
/

-- Least privilege for the runtime account.
DECLARE
  PROCEDURE g(p_sql VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  END;
BEGIN
  FOR t IN (SELECT column_value AS t FROM TABLE(sys.odcivarchar2list(
              'CUSTOMERS', 'PRODUCTS', 'ORDERS', 'ORDER_ITEMS', 'PAYMENTS', 'ALERTS',
              'CHANGE_REQUESTS', 'WEBHOOKS', 'WEBHOOK_DELIVERIES', 'TENANT_SETTINGS'))) LOOP
    g('GRANT SELECT, INSERT, UPDATE, DELETE ON ' || t.t || ' TO prov_app');
  END LOOP;
  FOR t IN (SELECT column_value AS t FROM TABLE(sys.odcivarchar2list(
              'CUSTOMERS', 'PRODUCTS', 'ORDERS', 'ORDER_ITEMS', 'PAYMENTS'))) LOOP
    g('GRANT FLASHBACK ON ' || t.t || ' TO prov_app');
  END LOOP;
  g('GRANT SELECT, INSERT, UPDATE ON tenants TO prov_app');
  g('GRANT SELECT, INSERT, UPDATE ON app_users TO prov_app');
  g('GRANT SELECT ON order_status_transitions TO prov_app');
  -- audit_log: read-only for the API. History can only be written by triggers.
  g('GRANT SELECT ON audit_log TO prov_app');
  g('GRANT SELECT ON outbox_events TO prov_app');
  g('GRANT UPDATE (dispatched_at) ON outbox_events TO prov_app');
  g('GRANT EXECUTE ON ctx_pkg TO prov_app');
  g('GRANT EXECUTE ON outbox_pkg TO prov_app');
  g('GRANT EXECUTE ON audit_api_pkg TO prov_app');
END;
/
